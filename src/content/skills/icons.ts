// Ink themes: every colour of an icon falls into one of four brightness bands, and the
// theme paints each band with its own key. 'k' stays the outline.
const BAND: Record<string, number> = {};
for (const ch of 'wYQim') BAND[ch] = 0;
for (const ch of 'lyLCcPhosT') BAND[ch] = 1;
for (const ch of 'gOGbrMvnSqt') BAND[ch] = 2;
for (const ch of 'dFBReNuHzDIjEApUaJ') BAND[ch] = 3;

export const INKS: Record<string, string> = {
  fire: 'Yyoq',
  ice: 'iCcb',
  poison: 'mLGF',
  blood: 'PrrR',
  gold: 'YyOS',
  shadow: 'Pvep',
  holy: 'wYys',
  earth: 'TsnN',
  storm: 'wCbB',
  nature: 'mLGE',
  neon: 'whMu',
  void: 'vMuH',
  steel: 'wlgd',
  rose: 'wPhM',
  sea: 'itAI',
  rust: 'TonU',
};

export function ink(rows: string[], theme?: string): string[] {
  const t = theme && INKS[theme];
  if (!t) return rows;
  return rows.map((r) => [...r].map((ch) => (ch in BAND ? t[BAND[ch]] : ch)).join(''));
}
