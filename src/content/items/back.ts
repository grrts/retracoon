// Back slot: packs, capes and wings, anchored behind the shoulders (11,12).
// Packs are drawn behind the raccoon and peek out between the tail (x1-9) and the head (x15+).
// Wings rise above the tail. Capes and shells drape over the back in front.
import type { ItemDef } from '../types';
import { over, tint } from './art';

// A wing that rises up and back from the shoulders: tip top-left, root bottom-right.
const WING = [
  'kkkk...........',
  'kaaakkk........',
  'kabbaaakk......',
  '.kbbbbbaakk....',
  '.kbbbbbbbaak...',
  'kkbbbbbbbbbak..',
  'kbbbbbbbbbbbak.',
  '.kbbbbbbbbbbbak',
  'kkbbkbbbbbbbbak',
  'kbbk.kbbkbbbbak',
  '.kk...kk.kbbbak',
  '.........kbbbk.',
  '..........kbbk.',
  '..........kbk..',
  '...........k...',
];
const wing = (map: Record<string, string>, extra: string[] = []) => {
  const rows = WING.map((r, y) => [...r].map((ch, x) => (extra[y]?.[x] && extra[y][x] !== '.' ? extra[y][x] : (map[ch] ?? ch))).join(''));
  // flap: the alt frame dips the wing two pixels
  const alt = ['.'.repeat(15), '.'.repeat(15), ...rows.slice(0, -2)];
  return { anchor: 'back' as const, x: -11, y: -18, behind: true, rows, alt };
};

