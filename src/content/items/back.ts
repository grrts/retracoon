const CAPE = [
  'kkk...............',
  'kaakkk............',
  'kbaaaakkk.........',
  '.kbbaaaaakkk......',
  'kbbbbbaaaaaakkk...',
  'kbkkbbbbbaaaaaakk.',
  '.k..kkkbbbbbaaaaak',
  '.......kkkbbbbbaak',
  '..........kkkbbbbk',
  '.............kkkk.',
];
const CAPE_ALT = [
  '..................',
  'kkkk..............',
  'kaaakkk...........',
  'kbbaaaaakkk.......',
  '.kbbbbaaaaaakkk...',
  'kbbkbbbbbaaaaaakk.',
  'kk.kkkkbbbbbaaaaak',
  '.......kkkbbbbbaak',
  '..........kkkbbbbk',
  '.............kkkk.',
];
const cape = (a: string, b: string, top: string[] = [], topAlt: string[] = top) => ({
  anchor: 'back' as const,
  x: -12,
  y: -12,
  behind: true,
  rows: over(tint(CAPE, { a, b }), top),
  alt: over(tint(CAPE_ALT, { a, b }), topAlt),
});

